package com.prism.rag.rag.chat;

/**
 * Prompt 模板。
 *
 * <p><b>提示词是 RAG 质量的第二个生死线</b>（第一个是分块）。</p>
 *
 * <p>三条核心规则：</p>
 * <ol>
 *   <li><b>只依据给定资料回答</b>：不给出处就"不知道"，而不是靠训练时的记忆瞎猜。
 *       这是抑制幻觉最有效的一句话。</li>
 *   <li><b>标注引用编号</b>：让模型在答案里标 [1] [2]，用户才能点回去核对。</li>
 *   <li><b>资料不足时明说</b>：宁可说"资料未覆盖"，也不要编。</li>
 * </ol>
 */
public final class PromptTemplates {

    private PromptTemplates() {
    }

    /**
     * RAG 问答系统提示词。
     */
    public static final String RAG_SYSTEM = """
            你是企业知识库助手，负责依据检索到的资料回答员工问题。

            回答规则：
            1. 只依据【参考资料】中的内容回答，不要使用你自己的先验知识补充或改写事实。
            2. 每一句关键结论后面用 [n] 标注来源编号，n 是参考资料前的序号。
            3. 如果参考资料不足以回答问题，直接说明"知识库中暂无相关资料"，并给出可以尝试的其它问法。
            4. 回答要简洁、结构清晰，优先使用要点列表，避免空话套话。
            5. 全部使用中文回答。
            """;

    /**
     * 深度思考模式提示词（让模型先拆解问题再检索）。
     */
    public static final String RAG_SYSTEM_DEEP = RAG_SYSTEM + """
            
            深度思考模式：
            - 先在心里拆解用户问题的关键检索点，再对照参考资料作答。
            - 如果问题包含多个子问题，逐条作答并分别标注引用。
            """;

    /**
     * 会话摘要提示词：把多轮对话压缩成一段摘要，代替原文进入 Prompt。
     */
    public static final String SUMMARY_SYSTEM = """
            请把下面的对话历史压缩成一段不超过 200 字的摘要，保留其中对后续问答有影响的事实性信息
            （如用户身份、已确认的约束条件、已得到的结论），忽略寒暄和重复内容。
            """;

    /**
     * 生成会话标题。
     */
    public static final String TITLE_SYSTEM = """
            请根据用户的第一个问题，生成一个不超过 20 字的会话标题，只输出标题本身。
            """;
}
